CREATE TABLE IF NOT EXISTS six_dim_schema (
    id            BIGSERIAL PRIMARY KEY,
    category_code VARCHAR(16)  NOT NULL,
    dim_key       VARCHAR(4)   NOT NULL,
    label         VARCHAR(64)  NOT NULL,
    description   VARCHAR(255) NOT NULL DEFAULT '',
    sort_order    INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT uk_six_dim_schema UNIQUE (category_code, dim_key)
);

COMMENT ON TABLE six_dim_schema IS '六维标签维度定义（品类 × A-F 维度键 → 标签/说明），替代前后端双写，新品类零代码上线';
COMMENT ON COLUMN six_dim_schema.category_code IS '品类码（GENERIC 为未知品类兜底定义）';
COMMENT ON COLUMN six_dim_schema.dim_key IS '维度键 A/B/C/D/E/F';
COMMENT ON COLUMN six_dim_schema.label IS '维度标签（如 轮廓形态、靠背/背部特征）';
COMMENT ON COLUMN six_dim_schema.description IS '维度说明（取值范围提示，用于 prompt 与前端展示）';

